"""Offline STEP 24 preparation. Never connects to a source or destination DB.

Input is an explicitly supplied, consistent snapshot (table -> list of row dicts).
Output uses parameter binding, preserves IDs and JSON bytes, and is not an app adapter.
"""
import json
import re
import sqlite3
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
EDITORIAL = ('users', 'sessions', 'login_limits', 'fact_reviews',
             'articles', 'revisions', 'reviews', 'audit')
TABLES = ('tracks', 'spotify_chart', 'youtube_stats') + EDITORIAL
JSON_COLUMNS = {'users': ('selection',), 'articles': ('evidence',),
                'revisions': ('snapshot',), 'reviews': ('checklist',),
                'fact_reviews': ('facts',), 'audit': ('data',)}


def columns():
    manifest = json.loads((ROOT / 'db/schema_manifest.json').read_text())
    result = {t: tuple(c['COLUMN_NAME'] for c in manifest['columns']
                       if c['TABLE_NAME'] == t) for t in TABLES[:3]}
    with sqlite3.connect(':memory:') as db:
        db.executescript((ROOT / 'db/migrations/002_editorial_sqlite.sql').read_text())
        result.update({t: tuple(r[1] for r in db.execute(f'PRAGMA table_info({t})'))
                       for t in EDITORIAL})
    return result


def schema_sql():
    """Derive reviewed source constraints; preserve JSON as text to avoid hash drift."""
    manifest = json.loads((ROOT / 'db/schema_manifest.json').read_text())
    statements = []
    for table in TABLES[:3]:
        fields = []
        for col in manifest['columns']:
            if col['TABLE_NAME'] != table:
                continue
            kind = {'int': 'INTEGER', 'bigint': 'BIGINT', 'date': 'DATE',
                    'datetime': 'TIMESTAMP WITHOUT TIME ZONE'}.get(
                        col['COLUMN_TYPE'], col['COLUMN_TYPE'])
            field = f"{col['COLUMN_NAME']} {kind} NOT NULL"
            if col['EXTRA'] == 'auto_increment':
                field = f"{col['COLUMN_NAME']} INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"
            fields.append(field)
        for fk in manifest['foreign_keys']:
            if fk['TABLE_NAME'] == table:
                fields.append(f"FOREIGN KEY ({fk['COLUMN_NAME']}) REFERENCES "
                              f"{fk['REFERENCED_TABLE_NAME']}({fk['REFERENCED_COLUMN_NAME']}) "
                              "ON UPDATE RESTRICT ON DELETE RESTRICT")
        indexes = {}
        for index in manifest['indexes']:
            if index['TABLE_NAME'] == table and index['INDEX_NAME'] != 'PRIMARY' and not index['NON_UNIQUE']:
                indexes.setdefault(index['INDEX_NAME'], []).append(index['COLUMN_NAME'])
        fields.extend(f"CONSTRAINT {name} UNIQUE ({','.join(cols)})" for name, cols in indexes.items())
        statements.append(f"CREATE TABLE {table} (\n  " + ',\n  '.join(fields) + '\n);')
    source = (ROOT / 'db/migrations/002_editorial_sqlite.sql').read_text()
    source = re.sub(r'--[^\n]*', '', source)
    source = re.sub(r'CREATE TRIGGER .*? END;', '', source)
    source = source.replace('id INTEGER PRIMARY KEY', 'id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY')
    source = re.sub(r'(\w+_id) INTEGER', r'\1 BIGINT', source)
    source = source.replace('expires_at INTEGER', 'expires_at BIGINT').replace('window_start INTEGER', 'window_start BIGINT')
    source = source.replace('DEFAULT CURRENT_TIMESTAMP',
                            "DEFAULT to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')")
    statements.append(source.strip())
    for table, cols in JSON_COLUMNS.items():
        for col in cols:
            statements.append(f'ALTER TABLE {table} ADD CONSTRAINT {table}_{col}_json CHECK ({col}::json IS NOT NULL);')
    statements.append("""CREATE FUNCTION reject_history_mutation() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN RAISE EXCEPTION 'immutable history'; END;
$$;""")
    for table in ('revisions', 'reviews', 'fact_reviews', 'audit'):
        statements.append(f'CREATE TRIGGER {table}_immutable BEFORE UPDATE OR DELETE OR TRUNCATE '
                          f'ON {table} FOR EACH STATEMENT EXECUTE FUNCTION reject_history_mutation();')
    return ('-- STEP 24: dedicated empty test database only. No automatic application migration.\n'
            '-- Run in one explicit transaction; do not use the table owner as an application role.\n'
            '-- JSON text and UTC text dates intentionally preserve existing signed evidence.\n'
            + '\n\n'.join(statements) + '\n')


def plan(snapshot):
    """Validate all eight editorial tables plus charts before producing INSERTs.

    No session invalidation or timestamp reinterpretation is silently performed.
    Values (including hashes) must never be logged.
    """
    if set(snapshot) != set(TABLES):
        raise ValueError('Snapshot must contain exactly all eleven tables')
    expected = columns()
    # SQLite source constraints provide an independent offline relation/role check.
    with sqlite3.connect(':memory:') as db:
        db.execute('PRAGMA foreign_keys=ON')
        db.executescript((ROOT / 'db/migrations/002_editorial_sqlite.sql').read_text())
        for table in EDITORIAL:
            for row in snapshot[table]:
                if set(row) != set(expected[table]):
                    raise ValueError(f'Column mismatch: {table}')
                for col in JSON_COLUMNS.get(table, ()):
                    json.loads(row[col], parse_constant=lambda _: (_ for _ in ()).throw(ValueError('Invalid JSON')))
                db.execute(f"INSERT INTO {table} ({','.join(expected[table])}) "
                           f"VALUES ({','.join('?' for _ in expected[table])})",
                           tuple(row[c] for c in expected[table]))
        if db.execute('PRAGMA foreign_key_check').fetchall():
            raise ValueError('Broken editorial relation')
    track_ids = {r['song_id'] for r in snapshot['tracks']}
    for row in snapshot['users']:
        selected = json.loads(row['selection'])
        if not isinstance(selected, list) or any(type(i) is not int or i not in track_ids for i in selected):
            raise ValueError('Selection references missing song_id')
    result = []
    for table in TABLES:
        seen = set()
        uniques = set()
        for row in snapshot[table]:
            if set(row) != set(expected[table]) or any(row[c] is None for c in expected[table]
                                                     if not (table == 'audit' and c == 'actor_id')):
                raise ValueError(f'Column/null mismatch: {table}')
            if table in TABLES[:3]:
                pk = row[expected[table][0]]
                if type(pk) is not int or pk in seen:
                    raise ValueError(f'Duplicate/invalid ID: {table}')
                seen.add(pk)
                if table != 'tracks':
                    if row['song_id'] not in track_ids:
                        raise ValueError('Broken song_id relation')
                    key = ((row['song_id'], row['chart_date']) if table == 'spotify_chart'
                           else (row['youtube_video_id'], row['collected_at']))
                    if key in uniques:
                        raise ValueError(f'Duplicate weekly key: {table}')
                    uniques.add(key)
            result.append((f"INSERT INTO {table} ({','.join(expected[table])}) "
                           f"VALUES ({','.join('%s' for _ in expected[table])})",
                           tuple(row[c] for c in expected[table])))
    return result


def sequence_sql():
    """After inserting preserved IDs; set an empty table's first generated ID to 1."""
    return '\n'.join(
        f"SELECT setval(pg_get_serial_sequence('{t}','{pk}'), "
        f"COALESCE((SELECT MAX({pk}) FROM {t}),1), EXISTS(SELECT 1 FROM {t}));"
        for t, pk in [('tracks', 'song_id'), ('spotify_chart', 'spotify_id'),
                      ('youtube_stats', 'youtube_id')] + [(t, 'id') for t in EDITORIAL
                                                          if t not in ('sessions', 'login_limits')])
