-- Run in one explicit transaction; do not use the table owner as an application role.
-- JSON text and UTC text dates intentionally preserve existing signed evidence.
CREATE TABLE tracks (
  song_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  artist varchar(255) NOT NULL,
  track varchar(255) NOT NULL
);

CREATE TABLE spotify_chart (
  spotify_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  song_id INTEGER NOT NULL,
  spotify_rank INTEGER NOT NULL,
  spotify_streams BIGINT NOT NULL,
  chart_date DATE NOT NULL,
  collected_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
  FOREIGN KEY (song_id) REFERENCES tracks(song_id) ON UPDATE RESTRICT ON DELETE RESTRICT,
  CONSTRAINT uq_spotify_song_chart UNIQUE (song_id,chart_date)
);

CREATE TABLE youtube_stats (
  youtube_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  song_id INTEGER NOT NULL,
  youtube_video_id varchar(50) NOT NULL,
  youtube_title varchar(500) NOT NULL,
  youtube_channel varchar(255) NOT NULL,
  youtube_views BIGINT NOT NULL,
  youtube_likes BIGINT NOT NULL,
  youtube_comments BIGINT NOT NULL,
  collected_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
  FOREIGN KEY (song_id) REFERENCES tracks(song_id) ON UPDATE RESTRICT ON DELETE RESTRICT,
  CONSTRAINT uq_youtube_video_collected UNIQUE (youtube_video_id,collected_at)
);

CREATE TABLE users (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, username TEXT NOT NULL UNIQUE, password_hash TEXT NOT NULL,
 role TEXT NOT NULL DEFAULT 'READER' CHECK(role IN ('READER','JOURNALIST','EDITOR','ADMIN')),
 selection TEXT NOT NULL DEFAULT '[]', created_at TEXT NOT NULL DEFAULT to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')
);
CREATE TABLE sessions (
 token_hash TEXT PRIMARY KEY, user_id BIGINT NOT NULL REFERENCES users(id), expires_at BIGINT NOT NULL
);
CREATE TABLE login_limits (key TEXT PRIMARY KEY, attempts INTEGER NOT NULL, window_start BIGINT NOT NULL);
CREATE TABLE fact_reviews (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, week_end TEXT NOT NULL, reviewer_id BIGINT NOT NULL REFERENCES users(id),
 facts TEXT NOT NULL, created_at TEXT NOT NULL DEFAULT to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')
);


CREATE TABLE articles (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, author_id BIGINT NOT NULL REFERENCES users(id), title TEXT NOT NULL,
 body TEXT NOT NULL, week_end TEXT NOT NULL, fact_ref TEXT NOT NULL, evidence TEXT NOT NULL,
 evidence_hash TEXT NOT NULL, version INTEGER NOT NULL DEFAULT 1,
 status TEXT NOT NULL CHECK(status IN ('DRAFT','PENDING_REVIEW','ON_HOLD','REVISED','APPROVED','WITHDRAWN')),
 created_at TEXT NOT NULL DEFAULT to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'), updated_at TEXT NOT NULL DEFAULT to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')
);
CREATE TABLE revisions (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, article_id BIGINT NOT NULL REFERENCES articles(id), version INTEGER NOT NULL,
 actor_id BIGINT NOT NULL REFERENCES users(id), snapshot TEXT NOT NULL,
 created_at TEXT NOT NULL DEFAULT to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'), UNIQUE(article_id,version)
);
CREATE TABLE reviews (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, article_id BIGINT NOT NULL REFERENCES articles(id), version INTEGER NOT NULL,
 reviewer_id BIGINT NOT NULL REFERENCES users(id), evidence_hash TEXT NOT NULL,
 checklist TEXT NOT NULL, comment TEXT NOT NULL, decision TEXT NOT NULL CHECK(decision IN ('APPROVED','ON_HOLD')),
 created_at TEXT NOT NULL DEFAULT to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')
);
CREATE TABLE audit (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, actor_id BIGINT REFERENCES users(id), action TEXT NOT NULL,
 target TEXT NOT NULL, data TEXT NOT NULL, created_at TEXT NOT NULL DEFAULT to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')
);

ALTER TABLE users ADD CONSTRAINT users_selection_json CHECK (selection::json IS NOT NULL);

ALTER TABLE articles ADD CONSTRAINT articles_evidence_json CHECK (evidence::json IS NOT NULL);

ALTER TABLE revisions ADD CONSTRAINT revisions_snapshot_json CHECK (snapshot::json IS NOT NULL);

ALTER TABLE reviews ADD CONSTRAINT reviews_checklist_json CHECK (checklist::json IS NOT NULL);

ALTER TABLE fact_reviews ADD CONSTRAINT fact_reviews_facts_json CHECK (facts::json IS NOT NULL);

ALTER TABLE audit ADD CONSTRAINT audit_data_json CHECK (data::json IS NOT NULL);

CREATE FUNCTION reject_history_mutation() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN RAISE EXCEPTION 'immutable history'; END;
$$;

CREATE TRIGGER revisions_immutable BEFORE UPDATE OR DELETE OR TRUNCATE ON revisions FOR EACH STATEMENT EXECUTE FUNCTION reject_history_mutation();

CREATE TRIGGER reviews_immutable BEFORE UPDATE OR DELETE OR TRUNCATE ON reviews FOR EACH STATEMENT EXECUTE FUNCTION reject_history_mutation();

CREATE TRIGGER fact_reviews_immutable BEFORE UPDATE OR DELETE OR TRUNCATE ON fact_reviews FOR EACH STATEMENT EXECUTE FUNCTION reject_history_mutation();

CREATE TRIGGER audit_immutable BEFORE UPDATE OR DELETE OR TRUNCATE ON audit FOR EACH STATEMENT EXECUTE FUNCTION reject_history_mutation();
